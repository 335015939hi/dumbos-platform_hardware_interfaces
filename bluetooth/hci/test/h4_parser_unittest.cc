TEST_F(H4ParserTest, CommandPacket) {
  std::vector<uint8_t> empty_command = {0x1, 0x03, 0x0c, 0x00};
  std::vector<uint8_t> small_command = {0x1, 0x03, 0x0c, 0x01, 0x0};

  EXPECT_CALL(callback_, Call(H4Parser::Idc::kCommand, Payload(empty_command)));
  EXPECT_CALL(callback_, Call(H4Parser::Idc::kCommand, Payload(small_command)));

  h4_parser_.Consume(empty_command);
  h4_parser_.Consume(small_command);
}

