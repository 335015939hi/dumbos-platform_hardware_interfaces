TEST_F(H4ParserTest, TruncatedPackets) {
  std::vector<uint8_t> small_sco_packet = {0x3,  0x2a, 0x00, 0x03,
                                           0x01, 0x02, 0x03};
  std::vector<uint8_t> input_stream;

  const int repeats = 6;
  const std::vector<size_t> slices = {1, 2, 4, 2, 5, 5, 2, 9, 9, 3};

  for (int n = 0; n < repeats; n++) {
    input_stream.insert(input_stream.end(), small_sco_packet.begin(),
                        small_sco_packet.end());
  }

  EXPECT_CALL(callback_, Call(H4Parser::Idc::kSco, Payload(small_sco_packet)))
      .Times(repeats);

  size_t offset = 0;
  for (size_t slice : slices) {
    h4_parser_.Consume(input_stream.data() + offset, slice);
    offset += slice;
  }

  ASSERT_EQ(offset, input_stream.size());
}
